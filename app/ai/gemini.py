async def parse_transactions(text: str) -> TransactionResult:
    response = await client.aio.models.generate_content(
        model=MODEL,
        contents=text,
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT,
            response_mime_type="application/json",
            response_schema=TransactionResult,
            temperature=0,
        ),
    )

    if response.parsed:
        if isinstance(response.parsed, TransactionResult):
            result = response.parsed
        else:
            result = TransactionResult.model_validate(
                response.parsed
            )

    elif response.text:
        result = TransactionResult.model_validate_json(
            response.text
        )

    else:
        raise ValueError("Gemini вернул пустой ответ")

    # Проверка транзакций
    for transaction in result.transactions:
        if transaction.amount <= 0:
            raise ValueError(
                f"Некорректная сумма транзакции: {transaction.amount}"
            )

    # Проверка создания цели
    if result.goal_creation:
        if result.goal_creation.target_amount <= 0:
            raise ValueError("Некорректная сумма цели")

    # Проверка пополнения цели
    if result.goal_contribution:
        if result.goal_contribution.amount <= 0:
            raise ValueError("Некорректная сумма пополнения")

    # Проверка процента отчисления
    if result.goal_allocation:
        percentage = result.goal_allocation.percentage

        if percentage <= 0 or percentage > 100:
            raise ValueError("Процент должен быть от 0 до 100")

        total_income = sum(
            (
                transaction.amount
                for transaction in result.transactions
                if transaction.type == "income"
            ),
            start=0,
        )

        if total_income <= 0:
            result.needs_clarification = True
            result.clarification_question = (
                "Не нашёл доход в сообщении. "
                "Какую сумму нужно распределить на цель?"
            )


    return result



